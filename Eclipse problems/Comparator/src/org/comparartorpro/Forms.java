package org.comparartorpro;

public class Forms {
	private String name;
	private int role;
	private int benchNo;
	public String getName() {
		return name;
	}
	public void setName(String name) {
		this.name = name;
	}
	public int getRole() {
		return role;
	}
	public void setRole(int role) {
		this.role = role;
	}
	public int getBenchNo() {
		return benchNo;
	}
	public void setBenchNo(int benchNo) {
		this.benchNo = benchNo;
	}
	
	
}
